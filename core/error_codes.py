from enum import IntEnum

class AppErrorCode(IntEnum):
    # 1000–1999: Generic/System
    GENERIC_ERROR = 1000
    VALIDATION_ERROR = 1001
    RESOURCE_NOT_FOUND = 1002
    PERMISSION_DENIED = 1003
    DATABASE_ERROR = 1004
    RATE_LIMIT_EXCEEDED = 1005
    INTERNAL_ERROR = 1006

    # 2000–2999: Orchestration & Tools
    TOOL_EXECUTION_ERROR = 2000
    TOOL_TIMEOUT = 2001
    TOOL_FORBIDDEN = 2002
    AGENT_ROUTING_FAILED = 2003
    PLANNING_ERROR = 2004
    PROVIDER_ERROR = 2005  # LLM/STT/TTS API failures

    # 3000–3999: Domain Specific (User, Session, Goal)
    SESSION_NOT_FOUND = 3000
    GOAL_NOT_FOUND = 3001
    INVALID_GOAL_STATE = 3002
    MEMORY_RETRIEVAL_FAILED = 3003
